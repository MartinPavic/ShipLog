import { AiCard, GitLabCard, GithubCard } from "@/components/settings-form";
import { ManageBillingButton, UpgradeButton } from "@/components/upgrade-button";
import { Badge } from "@/components/ui/badge";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { siteConfig } from "@/config/site";
import { features } from "@/env";
import { getOwner, isAdmin } from "@/lib/owner";
import type { AiMode, Plan } from "@/lib/plans";
import { getSetupStatus } from "@/lib/settings";

function BillingCard({
  plan,
  aiMode,
  usage,
  aiReady,
  demoAi,
  canManage,
}: {
  plan: Plan;
  aiMode: AiMode;
  usage: { used: number; limit: number | null };
  aiReady: boolean;
  demoAi: boolean;
  canManage: boolean;
}) {
  const isPaid = plan !== "free";
  const label = plan === "ultra" ? "Ultra" : plan === "pro" ? "Pro" : "Free";
  const modeLabel = aiMode === "managed" ? "Managed AI" : "BYOK";
  const allowanceLabel = `${usage.used} / ${usage.limit === null ? "Unlimited" : usage.limit} generations this month`;

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          Billing
          <Badge variant={isPaid ? "default" : "secondary"}>{label}</Badge>
        </CardTitle>
        <CardDescription>
          {isPaid
            ? "Manage your subscription, payment method and invoices."
            : "Upgrade for more projects and full history. Bring your own AI key in Settings to generate reports."}
        </CardDescription>
      </CardHeader>
      <CardContent>
        <div className="mb-4 space-y-1 text-sm text-muted-foreground">
          {isPaid && <p>AI mode: {modeLabel}</p>}
          <p>Allowance: {allowanceLabel}</p>
        </div>
        <div className="mb-4 space-y-1 text-sm text-muted-foreground">
          {!isPaid || aiMode === "byok" ? (
            <p>BYOK mode requires a workspace AI key.</p>
          ) : (
            <p>Managed AI mode uses the deployment key and ignores any saved workspace key.</p>
          )}
          {isPaid && <p>Switch AI mode through subscription management.</p>}
        </div>
        {aiMode === "managed" && !demoAi && !aiReady && (
          <p className="mb-4 text-sm text-danger">
            {canManage
              ? "Managed AI is unavailable on this deployment. Configure the server AI key or switch this workspace to BYOK mode."
              : "Managed AI is unavailable on this deployment. Contact your organization admin."}
          </p>
        )}
        {!canManage ? (
          <p className="text-sm text-muted-foreground">Only organization admins can manage billing.</p>
        ) : isPaid ? (
          <ManageBillingButton />
        ) : (
          <UpgradeButton />
        )}
      </CardContent>
    </Card>
  );
}

export default async function SettingsPage({
  searchParams,
}: {
  searchParams: Promise<{ github?: string; gitlab?: string }>;
}) {
  const { github: githubNotice, gitlab: gitlabNotice } = await searchParams;
  const owner = await getOwner();
  const status = await getSetupStatus(owner);
  const canManage = isAdmin(owner);

  return (
    <div className="max-w-2xl space-y-6">
      <div>
        <h1 className="text-2xl font-bold mb-2">Settings</h1>
        <p className="text-muted-foreground">
          Connect your source control and AI provider so {siteConfig.name} can generate reports.
        </p>
        {owner.orgId && (
          <p className="mt-2 text-sm text-muted-foreground">
            You are in an organization workspace. The AI key and the subscription are shared by the whole
            organization and managed by its admins. Billing is flat per organization, not per member. GitHub
            connections stay personal: each member connects their own.
          </p>
        )}
      </div>

      <GithubCard login={status.github?.login ?? null} notice={githubNotice ?? null} />
      <GitLabCard
        instance={status.gitlab.instance}
        username={status.gitlab.connection?.username ?? null}
        notice={gitlabNotice ?? null}
        canManage={canManage}
      />
      {status.demoAi ? (
        <Card>
          <CardHeader>
            <CardTitle>AI provider</CardTitle>
            <CardDescription>
              This deployment runs in demo mode: logs are generated by a built-in placeholder, so no API key is needed.
            </CardDescription>
          </CardHeader>
        </Card>
      ) : (
        <AiCard ai={status.ai} canManage={canManage} />
      )}

      {features().billing && (
        <BillingCard
          plan={status.plan}
          aiMode={status.aiMode}
          usage={status.usage}
          aiReady={status.aiReady}
          demoAi={status.demoAi}
          canManage={canManage}
        />
      )}
    </div>
  );
}
